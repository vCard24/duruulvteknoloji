if (require.main === module) {
  const fs = require('fs');
  const path = require('path');

  const ROOT = path.join(__dirname, '..');
  const faqs = module.exports;

  for (const locale of ['en', 'ar']) {
    const filePath = path.join(ROOT, 'assets', 'data', `urunler.${locale}.json`);
    const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));
    const map = faqs[locale];
    let updated = 0;

    for (const product of data.urunler) {
      const list = map[product.slug];
      if (!list) {
        console.warn(`[${locale}] missing FAQs for slug: ${product.slug}`);
        continue;
      }
      product.faqs = list;
      updated += 1;
    }

    fs.writeFileSync(filePath, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
    console.log(`${locale}: updated ${updated} products → ${path.relative(ROOT, filePath)}`);
  }
}
